"use client";

import { useState } from "react";
import { Info } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Field, Input, Select } from "@/components/ui/field";
import { trpc } from "@/lib/trpc/client";
import { cn } from "@/lib/utils";

function defaultCycle() {
  const now = new Date();
  const half = now.getMonth() < 6 ? "H1" : "H2";
  return `FY${String(now.getFullYear()).slice(2)}-${half}`;
}

function halfBounds(cycleLabel: string) {
  // Parses FY27-H1. Falls back to the current half when the label is bespoke,
  // which HR labels often are.
  const match = /FY(\d{2})-(H[12])/.exec(cycleLabel);
  const now = new Date();
  const year = match ? 2000 + Number(match[1]) : now.getFullYear();
  const firstHalf = match ? match[2] === "H1" : now.getMonth() < 6;
  return {
    periodStart: new Date(year, firstHalf ? 0 : 6, 1, 0, 0, 0, 0),
    periodEnd: new Date(year, firstHalf ? 6 : 12, 0, 23, 59, 59, 999),
  };
}

export default function AppraisalPage() {
  const utils = trpc.useUtils();
  const [cycleLabel, setCycleLabel] = useState(defaultCycle());
  const [departmentId, setDepartmentId] = useState("");
  const [error, setError] = useState<string | null>(null);

  const departments = trpc.reference.departments.useQuery();
  const cycle = trpc.appraisal.listCycle.useQuery({ cycleLabel });

  const generate = trpc.appraisal.generateForDepartment.useMutation({
    onSuccess: () => {
      setError(null);
      utils.appraisal.listCycle.invalidate();
    },
    onError: (e) => setError(e.message),
  });

  if (cycle.error) {
    const code = cycle.error.data?.code;
    return (
      <Card className="flex flex-col items-center gap-2 px-6 py-14 text-center">
        <p className="text-sm font-medium">
          {code === "UNAUTHORIZED"
            ? "Sign in to continue"
            : code === "FORBIDDEN"
              ? "Not available to your role"
              : "Could not load the cycle"}
        </p>
        <p className="max-w-md text-xs text-muted-foreground">
          {code === "FORBIDDEN"
            ? "Appraisal evidence is generated by HR, Audit or an executive. A line manager reads the same figures on their team member's report card."
            : cycle.error.message}
        </p>
      </Card>
    );
  }

  const rows = cycle.data ?? [];
  const insufficient = rows.filter((r) => !r.hasSufficientVolume).length;
  const undisclosed = rows.filter((r) => !r.disclosedToSubjectAt).length;

  return (
    <div className="flex flex-col gap-4">
      {error && (
        <div className="rounded-md border border-danger/30 bg-danger-subtle px-3 py-2 text-xs text-danger">
          {error}
        </div>
      )}

      <Card>
        <CardContent className="flex flex-wrap items-end gap-3 py-4">
          <Field label="Cycle" htmlFor="cycle" className="w-40">
            <Input id="cycle" value={cycleLabel} onChange={(e) => setCycleLabel(e.target.value)} />
          </Field>
          <Field label="Department" htmlFor="dept" className="w-56">
            <Select id="dept" value={departmentId} onChange={(e) => setDepartmentId(e.target.value)}>
              <option value="">Select a department…</option>
              {(departments.data ?? []).map((d) => (
                <option key={d.id} value={d.id}>
                  {d.name}
                </option>
              ))}
            </Select>
          </Field>
          <Button
            size="sm"
            disabled={!departmentId || !cycleLabel.trim() || generate.isPending}
            onClick={() =>
              generate.mutate({ departmentId, cycleLabel, ...halfBounds(cycleLabel) })
            }
          >
            Generate evidence
          </Button>
        </CardContent>
      </Card>

      {rows.length > 0 && (
        <Card>
          <CardContent className="flex flex-wrap gap-x-10 gap-y-3">
            <Metric label="Snapshots" value={rows.length} />
            <Metric
              label="Insufficient data"
              value={insufficient}
              tone={insufficient > 0 ? "warning" : undefined}
            />
            <Metric
              label="Not yet seen by subject"
              value={undisclosed}
              tone={undisclosed > 0 ? "warning" : undefined}
            />
          </CardContent>
        </Card>
      )}

      <Card className="overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left">
            <thead>
              <tr className="border-b border-border bg-muted/40">
                <th className="label-caps px-4 py-2.5">Employee</th>
                <th className="label-caps px-4 py-2.5 text-right">Execution</th>
                <th className="label-caps px-4 py-2.5 text-right">Timeliness</th>
                <th className="label-caps px-4 py-2.5 text-right">Quality</th>
                <th className="label-caps px-4 py-2.5 text-right">Governance</th>
                <th className="label-caps px-4 py-2.5 text-right">Contribution</th>
                <th className="label-caps px-4 py-2.5 text-right">Excluded</th>
                <th className="label-caps px-4 py-2.5">Disclosed</th>
              </tr>
            </thead>
            <tbody>
              {rows.map((r) => (
                <tr key={r.id} className="border-b border-border last:border-b-0 hover:bg-muted/40">
                  <td className="px-4 py-2.5">
                    <div className="flex flex-col gap-0.5">
                      <span className="text-sm font-medium">{r.employee.name}</span>
                      {r.employee.designation && (
                        <span className="text-2xs text-muted-foreground">{r.employee.designation}</span>
                      )}
                    </div>
                  </td>
                  {r.hasSufficientVolume ? (
                    <>
                      <Pct value={r.execution} />
                      <Pct value={r.timeliness} />
                      <Pct value={r.quality} />
                      <Pct value={r.governance} />
                      <Pct value={r.contribution} />
                    </>
                  ) : (
                    <td colSpan={5} className="px-4 py-2.5 text-center text-2xs text-muted-foreground">
                      Not enough work in this period to report on
                    </td>
                  )}
                  <td
                    className={cn(
                      "px-4 py-2.5 text-right text-xs tabular",
                      r.excludedTaskCount > 0 && "text-warning",
                    )}
                  >
                    {r.excludedTaskCount}
                  </td>
                  <td className="px-4 py-2.5">
                    {r.disclosedToSubjectAt ? (
                      <Badge tone="success">seen</Badge>
                    ) : (
                      <Badge tone="warning">not yet</Badge>
                    )}
                  </td>
                </tr>
              ))}
              {!cycle.isLoading && rows.length === 0 && (
                <tr>
                  <td colSpan={8} className="px-4 py-10 text-center text-xs text-muted-foreground">
                    No evidence generated for {cycleLabel} yet.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </Card>

      <Card>
        <CardContent className="flex gap-3 py-4">
          <Info className="mt-0.5 size-4 shrink-0 text-muted-foreground" aria-hidden />
          <div className="flex flex-col gap-1.5 text-2xs text-muted-foreground">
            <p>
              <span className="font-medium text-foreground">This is evidence, not a score.</span> No
              weighted performance figure is computed or exposed. The five components are read
              alongside the work behind them, and each one is drillable to the tasks that produced it.
            </p>
            <p>
              Every snapshot is fixed at the moment it was generated, so an appraisal conversation
              references a stable artifact rather than a figure that moves. Generating one is audited,
              and the subject seeing their own is recorded — they are never shown figures their
              manager has not seen, or kept from figures their manager has.
            </p>
          </div>
        </CardContent>
      </Card>
    </div>
  );
}

function Pct({ value }: { value: number | null }) {
  return (
    <td className="px-4 py-2.5 text-right text-xs tabular">
      {value === null ? "—" : `${Math.round(value * 100)}%`}
    </td>
  );
}

function Metric({
  label,
  value,
  tone,
}: {
  label: string;
  value: number;
  tone?: "danger" | "warning";
}) {
  return (
    <div className="flex flex-col gap-0.5">
      <span className="label-caps">{label}</span>
      <span
        className={cn(
          "text-xl font-semibold tabular",
          tone === "danger" && "text-danger",
          tone === "warning" && "text-warning",
        )}
      >
        {value}
      </span>
    </div>
  );
}
