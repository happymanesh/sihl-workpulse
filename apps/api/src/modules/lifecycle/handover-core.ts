import {
  DaciRole,
  HandoverItemDisposition,
  HandoverItemType,
  HandoverReason,
  Priority,
} from "@workpulse/db";

/**
 * The rules deciding, for one thing a person holds, whether it moves to someone
 * else and whether the handover can complete without it.
 *
 * Pure and dependency-free, because this is the part that is easy to get subtly
 * wrong and expensive to discover later: a rule that wrongly RETAINS a desk card
 * leaves a seat nobody occupies, and one that wrongly HANDS OVER a project role
 * strips someone of work they are still doing.
 *
 * The governing distinction is whether the person is still at SIHL:
 *
 *   EXIT               they are leaving, so everything they hold must go.
 *   INTERNAL_TRANSFER  they are staying, so departmental duties go and the work
 *                      that is genuinely theirs travels with them.
 *   ROLE_CHANGE        same department, new seat: the desk card and the work it
 *                      generated go; almost nothing else does.
 */

export interface HeldItem {
  itemType: HandoverItemType;
  /** Priority of the underlying task. Only set for OPEN_TASK. */
  priority?: Priority | null;
  /** Task type code, e.g. "MANAGEMENT". Only set for OPEN_TASK. */
  taskTypeCode?: string | null;
  /** Department the task belongs to. Only set for OPEN_TASK. */
  taskDepartmentId?: string | null;
  /** Whether the task was generated by a desk card the person is giving up. */
  fromOutgoingDeskCard?: boolean;
  /** RACI role name, e.g. "ACCOUNTABLE". Only set for RACI_ROLE. */
  raciRole?: string | null;
  /** DACI role. Only set for DACI_ROLE. */
  daciRole?: DaciRole | null;
  /** Whether the decision behind a DACI role is still open. */
  decisionIsOpen?: boolean;
}

export interface HandoverContext {
  reason: HandoverReason;
  /** The department the person is leaving. Null when unknown. */
  fromDepartmentId: string | null;
}

export interface Verdict {
  disposition: HandoverItemDisposition;
  isBlocking: boolean;
}

const HAND_OVER = HandoverItemDisposition.HAND_OVER;
const RETAINED = HandoverItemDisposition.RETAINED;

/** A task nobody can afford to leave in limbo. */
function isConsequentialTask(item: HeldItem): boolean {
  return item.priority === Priority.CRITICAL || item.taskTypeCode === "MANAGEMENT";
}

export function decide(item: HeldItem, ctx: HandoverContext): Verdict {
  const staying = ctx.reason !== HandoverReason.EXIT;

  switch (item.itemType) {
    // A desk card is attached to the seat, never to the person. It moves in
    // every case, and it blocks in every case - an unoccupied desk card means
    // its recurring obligations stop generating and nobody notices for a month.
    case HandoverItemType.DESK_CARD_HOLDER:
      return { disposition: HAND_OVER, isBlocking: true };

    // Recurring activities follow their desk card rather than being transferred
    // individually, so they are listed for visibility and never block.
    case HandoverItemType.RECURRING_ACTIVITY:
      return { disposition: HAND_OVER, isBlocking: false };

    case HandoverItemType.OPEN_TASK: {
      if (!staying) {
        return { disposition: HAND_OVER, isBlocking: isConsequentialTask(item) };
      }
      // Staying. Work generated by the desk card they are giving up goes with
      // the desk card; so does anything belonging to the department they are
      // leaving. Everything else is their own work and travels with them.
      const belongsToOldSeat =
        item.fromOutgoingDeskCard === true ||
        (ctx.reason === HandoverReason.INTERNAL_TRANSFER &&
          ctx.fromDepartmentId !== null &&
          item.taskDepartmentId === ctx.fromDepartmentId);

      if (!belongsToOldSeat) return { disposition: RETAINED, isBlocking: false };
      return { disposition: HAND_OVER, isBlocking: isConsequentialTask(item) };
    }

    // Project accountability is held by a person, not by a department. Someone
    // moving between departments usually stays on the project - stripping them
    // of it because they changed desk would be wrong, and would leave the
    // project without an accountable owner for no reason.
    case HandoverItemType.RACI_ROLE:
      if (staying) return { disposition: RETAINED, isBlocking: false };
      // Leaving: accountability cannot be left vacant.
      return { disposition: HAND_OVER, isBlocking: item.raciRole === "ACCOUNTABLE" };

    case HandoverItemType.DACI_ROLE:
      if (staying) return { disposition: RETAINED, isBlocking: false };
      return {
        disposition: HAND_OVER,
        // A pending decision whose approver has left can never be closed.
        isBlocking: item.daciRole === DaciRole.APPROVER && item.decisionIsOpen === true,
      };

    // Ownership of a process or policy is a control, and an unowned control is
    // a compliance gap whether the owner left the company or just the floor.
    case HandoverItemType.PROCESS_OWNER:
    case HandoverItemType.POLICY_OWNER:
      return { disposition: HAND_OVER, isBlocking: true };

    case HandoverItemType.PENDING_APPROVAL:
      return { disposition: HAND_OVER, isBlocking: !staying };

    // Cover arrangements are informational either way.
    case HandoverItemType.DELEGATION:
      return { disposition: HAND_OVER, isBlocking: false };

    default:
      return { disposition: HAND_OVER, isBlocking: false };
  }
}

/**
 * Nothing retained can block. There is no second party to wait for, so a
 * blocking retained item would be an exit condition that can never be met.
 * Applied centrally so a future rule cannot reintroduce the deadlock.
 */
export function normalise(v: Verdict): Verdict {
  return v.disposition === RETAINED ? { ...v, isBlocking: false } : v;
}

export function decideFor(item: HeldItem, ctx: HandoverContext): Verdict {
  return normalise(decide(item, ctx));
}

/**
 * Whether both managers have signed. Only an internal move needs two: an exit
 * has no receiving manager, and a role change stays under the same one.
 */
export function needsDualApproval(reason: HandoverReason): boolean {
  return reason === HandoverReason.INTERNAL_TRANSFER;
}
